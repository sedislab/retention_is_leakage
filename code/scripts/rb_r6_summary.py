#!/usr/bin/env python3
"""R6 (`rebuttal/REBUTTAL_EXPERIMENTS.md` §10): writes `rebuttal/RESULTS_SUMMARY.md` from the
rebuttal CSVs only. It computes nothing beyond means and intervals over seeds. Every table names its
source file and row filter. Intervals: 95% Student-t over seeds (n = 3) for accuracies; R1 uses the
2,000-replicate hierarchical bootstrap already in the CSV. PBS only.
"""
from __future__ import annotations

import csv
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np
from scipy import stats

REPO_ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO_ROOT / "code" / "src"))

from p3fcl import provenance  # noqa: E402
from p3fcl.rebuttal.common import manifest  # noqa: E402

OUT = REPO_ROOT / "rebuttal" / "RESULTS_SUMMARY.md"


def rows(name):
    p = REPO_ROOT / name
    if not p.exists():
        return []
    with open(p, newline="") as f:
        return list(csv.DictReader(f))


def ci(vals):
    v = np.asarray(vals, dtype=float)
    m = float(v.mean())
    if len(v) < 2:
        return m, float("nan"), float("nan")
    h = float(stats.t.ppf(0.975, len(v) - 1) * v.std(ddof=1) / np.sqrt(len(v)))
    return m, m - h, m + h


def fmt(vals):
    m, lo, hi = ci(vals)
    return f"{m:.3f} [{lo:.3f}, {hi:.3f}]"


def group(rs, keys, val="final_avg_acc"):
    g = defaultdict(list)
    for r in rs:
        g[tuple(r[k] for k in keys)].append(float(r[val]))
    return g


def table(header, body):
    lines = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in body]
    return "\n".join(lines)


def main() -> int:
    man = manifest({"seed": 0, "purpose": "rebuttal R6 results summary"})
    md = ["# Rebuttal results summary (generated by `code/scripts/rb_r6_summary.py`; do not edit by hand)", "",
          "Means over seeds {0, 1, 2} with 95% Student-t intervals over seeds, unless stated. With 3 seeds these intervals are wide and are "
          "not clipped to [0, 1]. Protocols: "
          "`rebuttal/R{1..5}_PROTOCOL.md`. Notes: `notes/2026-11-06_rb_*.md`. Code-reading answers: `rebuttal/answers.md`.", ""]

    # R0
    r0 = rows("rebuttal/r0_check.csv")
    md += ["## R0 reproduction check (GATE, approved 2026-11-06)", "",
           f"Source: `rebuttal/r0_check.csv` (all rows). {sum(int(r['pass']) for r in r0)}/{len(r0)} values equal the committed "
           f"`results/m9_sweep_<ds>.csv` rows; max |diff| = {max(float(r['abs_diff']) for r in r0):.1e}.", ""]

    # R1
    r1 = rows("results/rb_release_audit.csv")
    body = []
    for r in r1:
        if r["ablation"] == "trajectory" and (r["elapsed"] == "0" or (r["elapsed"] == "6" and r["view"] in ("margin_repro", "combined", "combined_once"))):
            body.append([r["dataset"], r["method"], r["view"], r["elapsed"],
                         f"{float(r['tpr1']):.3f} [{float(r['tpr1_ci_lo']):.3f}, {float(r['tpr1_ci_hi']):.3f}]",
                         f"{float(r['tpr01']):.3f}", f"{float(r['auc']):.3f}", f"{float(r['paper_margin_tpr1_e6']):.3f}",
                         r["prediction_holds"], r["check"]])
    n_pred = [r for r in r1 if r["prediction_holds"] not in ("n/a", "")]
    md += ["## R1 release-only audit of M2/M3 (mjT5 main concern)", "",
           "Source: `results/rb_release_audit.csv`, filter `ablation == trajectory`, elapsed 0 (and 6 for the margin and combined views). "
           "TPR@1%FPR with a 95% hierarchical-bootstrap interval (2,000 replicates; 3 seeds × targets).", "",
           f"**Prediction (release TPR@1%FPR at e = 0 ≥ paper margin TPR@1%FPR at e = 6): held in "
           f"{sum(int(r['prediction_holds']) for r in n_pred)}/{len(n_pred)} cells.** Every `margin_repro` row equals the paper's "
           "`a1_lira_fixedk_summary_<ds>_<method>_full.csv`. Every release view is constant in e.", "",
           table(["dataset", "method", "view", "e", "TPR@1%FPR [95% CI]", "TPR@0.1%FPR", "AUC", "paper margin e=6", "prediction holds", "check"], body), ""]

    # R2
    r2 = rows("results/rb_projection_ablation.csv")
    g = group(r2, ["dataset", "arm", "unit", "eps"])
    p_of = {(r["dataset"], r["arm"], r["unit"], r["eps"]): r["selected_p"] for r in r2}
    cells = [("U1", "1.0"), ("U1", "2.0"), ("U1", "4.0"), ("U1", "8.0"), ("U1", "inf"), ("U2", "8.0")]
    body = [[ds, arm] + [f"{fmt(g[(ds, arm, u, e)])} (p={p_of[(ds, arm, u, e)]})" for u, e in cells]
            for ds in ("cifar100", "cub200", "imagenet_r") for arm in ("pca_id", "no_proj", "pca_ood", "random_proj") if (ds, arm, "U1", "1.0") in g]
    md += ["## R2 projection ablation and OOD public data (Reviewer 1 W1, mjT5 Q1)", "",
           "Source: `results/rb_projection_ablation.csv`, grouped by (dataset, arm, unit, eps), final_avg_acc. "
           "Selection grid: `results/rb_projection_ablation_selection.csv`. No prediction was stated.", "",
           table(["dataset", "arm"] + [f"{u} ε0={e}" for u, e in cells], body), ""]

    # R3
    r3 = rows("results/rb_client_scaling.csv")
    g = group(r3, ["dataset", "calibration", "eps", "n_clients"])
    clip = group([r for r in r3 if r["frac_clipped"] not in ("", "None")], ["dataset", "calibration", "eps", "n_clients"], "frac_clipped")
    body = []
    for ds in ("cifar100", "cub200", "imagenet_r"):
        ns = sorted({int(k[3]) for k in g if k[0] == ds})
        for cal in ("old_fixed_C", "size_matched", "u1_reference", "m8_reference"):
            for e in (("inf",) if cal == "m8_reference" else ("1.0", "4.0", "8.0")):
                for n in ns:
                    k = (ds, cal, e, str(n))
                    if k in g:
                        body.append([ds, cal, e, n, fmt(g[k]), f"{np.mean(clip[k]):.2f}" if k in clip else "–"])
    md += ["## R3 client-level privacy as n grows (mjT5 units, Reviewer 1 W2)", "",
           "Source: `results/rb_client_scaling.csv`, grouped by (dataset, calibration, eps, n_clients), final_avg_acc. "
           "Clipped fraction = mean `frac_clipped`. Selection and C(n, p): `results/rb_client_scaling_selection.csv`. "
           f"{sum(r['paper_check'] == 'matches_paper' for r in r3)} rows equal the paper's sweep bit for bit. No prediction was stated.", "",
           table(["dataset", "calibration", "ε0", "n", "final avg acc [95% CI]", "clipped frac"], body), ""]

    # R4
    r4 = rows("results/rb_examples_per_class.csv")
    g = group(r4, ["method", "eps", "m_per_class"])
    body = [[meth, e] + [fmt(g[(meth, e, m)]) for m in ("25", "50", "120", "250", "all")]
            for meth, e in (("m9_contractive", "1.0"), ("m9_contractive", "4.0"), ("m9_contractive", "8.0"), ("m9_contractive", "inf"), ("m8_analytic", "inf"))]
    pred = rows("results/rb_examples_per_class_prediction.csv")
    md += ["## R4 accuracy vs examples per class, CIFAR-100 (Reviewer 1 W2)", "",
           "Source: `results/rb_examples_per_class.csv`, grouped by (method, eps, m_per_class); prediction: "
           "`results/rb_examples_per_class_prediction.csv`.", "",
           table(["method", "ε0", "m=25", "m=50", "m=120", "m=250", "m=all"], body), "",
           f"**Prediction (accuracy depends on examples per class, not on the dataset): "
           f"{'HELD' if pred and pred[0]['prediction_holds'] == '1' else 'DID NOT HOLD'}.** "
           + "; ".join(f"ε0={p['eps']}: CIFAR m=25 {float(p['cifar_m25_mean']):.3f} vs CUB {float(p['cub_paper_mean']):.3f} vs CIFAR all "
                       f"{float(p['cifar_all_mean']):.3f}" for p in pred)
           + (f"; M8 m=25 {float(pred[0]['m8_m25_mean']):.3f} vs all {float(pred[0]['m8_all_mean']):.3f}." if pred else ""), ""]

    # R5
    r5 = rows("results/rb_dp_fedavg.csv") + [dict(r) for r in rows("results/rb_dp_fedavg_nscale.csv")]
    for r in r5:
        r.setdefault("n_clients", "10")
    body = []
    gA, gB, gN = (group(r5, ["dataset", "method", "n_clients", "eps"], v) for v in ("final_avg_acc", "bwt", "newest_task_acc"))
    for k in sorted(gA):
        body.append(list(k) + [fmt(gA[k]), fmt(gB[k]), fmt(gN[k])])
    m_t = {r["ledger_max_m_T"] for r in r5 if r.get("ledger_max_m_T") not in ("", None)}
    md += ["## R5 DP-FedAvg baselines at matched ε (Reviewer 1 W3)", "",
           "Source: `results/rb_dp_fedavg.csv` and `results/rb_dp_fedavg_nscale.csv`, grouped by (dataset, method, n_clients, eps). "
           "DP-FedAvg uses McMahan et al.'s fixed-denominator weighted mean (`rebuttal/R5_PROTOCOL.md` amendments 1–2; this deviates from "
           "the plan, see `rebuttal/answers.md`). Correctness gate: `rebuttal/r5_gate.csv`. "
           f"Ledger max m_T over runs: {sorted(m_t) if m_t else 'n/a'} (1 means lifelong ε = ε0).", ""]
    sel = rows("results/rb_dp_fedavg_selection.csv") + rows("results/rb_dp_fedavg_nscale_selection.csv")
    best = defaultdict(float)
    for r in sel:
        if r["eps"] != "inf":
            k = (r["dataset"], r.get("n_clients") or "10", r["method"], r["eps"])
            best[k] = max(best[k], float(r["ref_val_final_avg_acc"]))
    if best:
        md += [f"Selection caveat: in {sum(v < 0.06 for v in best.values())}/{len(best)} finite-ε selection cells, the best ref-val "
               f"accuracy was below 0.06 (max {max(best.values()):.3f}). Sources: `results/rb_dp_fedavg_selection.csv` and "
               "`results/rb_dp_fedavg_nscale_selection.csv`, where `ref_val_final_avg_acc` is the max per (dataset, n, method, eps). "
               "So selection at finite ε is close to arbitrary, and ties resolve to the first grid point (lr = 0.1, multiplier 0.25).", ""]
    md += [
           table(["dataset", "method", "n", "ε0", "final avg acc [95% CI]", "BWT [95% CI]", "newest-task acc [95% CI]"], body) if body else "_pending_", ""]

    # R7
    r7 = rows("results/rb_sensitivity.csv")
    if r7:
        cells = {}
        for r in r7:
            cells.setdefault((r["method"], r["dataset"], r["n_clients"], r["eps"]), {})[r["role"]] = r
        body = []
        for k, v in cells.items():
            b = v["best"]
            pt = f"lr={b['lr']}, mult={b['clip_multiplier']}" if b["p"] == "n/a" else f"p={b['p']}, λ={b['lambda']}"
            f3 = lambda x: f"{float(x['final_avg_acc_mean']):.3f} [{float(x['ci_lo']):.3f}, {float(x['ci_hi']):.3f}]"  # noqa: E731
            body.append(list(k) + [f3(v["selected"]), f"{v['selected']['selected_rank_oracle']}/{v['selected']['n_grid_points']}",
                                   f3(b), pt, f3(v["worst"])])
        n_match = sum(r["selected_rerun_matches_reported"] == "1" for r in r7 if r["role"] == "selected")
        md += ["## R7 test-split sensitivity of the selection grids (sensitivity, NOT selection)", "",
               "Source: `results/rb_sensitivity.csv` (all grid points × seeds: `results/rb_sensitivity_grid.csv`); protocol "
               "`rebuttal/R7_PROTOCOL.md`. **The 'best' column is a test-oracle upper bound, not used for selection.** Reported results "
               f"are unchanged; the rerun of every selected point equals the reported value bit for bit ({n_match}/{len(cells)} cells).", "",
               table(["method", "dataset", "n", "ε0", "selected (reported)", "selected oracle rank", "best (test-oracle upper bound, not used for selection)",
                      "best grid point", "worst"], body), ""]

    # R7b
    r7b = rows("results/rb_sensitivity_ext.csv")
    if r7b:
        f3 = lambda r: f"{float(r['best_final_avg_acc_mean']):.3f} [{float(r['ci_lo']):.3f}, {float(r['ci_hi']):.3f}]"  # noqa: E731
        body = [[r["method"], r["dataset"], r["n_clients"], r["eps"], f"{float(r['selected_reported_mean']):.3f}",
                 f"{float(r['r7_15pt_best_mean']):.3f}", f3(r), f"lr={r['best_lr']}, mult={r['best_clip_multiplier']}",
                 "yes" if r["interior"] == "1" else f"no ({r['edges_hit']})", r["extension_rounds"],
                 f"{float(r['best_bwt_mean']):.3f}"] for r in r7b]
        n_int = sum(r["interior"] == "1" for r in r7b)
        md += ["## R7b extended sensitivity grid for the DP baselines (sensitivity, NOT selection)", "",
               "Source: `results/rb_sensitivity_ext.csv` (all points × seeds: `results/rb_sensitivity_ext_grid.csv`); protocol "
               "`rebuttal/R7b_PROTOCOL.md`. **The best column is a test-oracle upper bound, not used for selection.** "
               f"The best point is interior in {n_int}/{len(r7b)} cells after up to 2 edge extensions. Where it is not, the true "
               "grid optimum may be higher still. The selected (reported) values are unchanged.", "",
               table(["method", "dataset", "n", "ε0", "selected (reported)", "R7 15-pt best", "R7b best (test-oracle upper bound, not used for selection)",
                      "best point", "interior", "ext. rounds", "best BWT"], body), ""]

    # R8
    r8 = rows("results/rb_r8_summary.csv")
    if r8:
        fv = lambda v: "n/a" if v in ("n/a", "") else f"{float(v):.3f}"  # noqa: E731
        ci3 = lambda r: f"{float(r['final_avg_acc_mean']):.3f} [{float(r['ci_lo']):.3f}, {float(r['ci_hi']):.3f}]"  # noqa: E731
        idx = {(r["method"], r["unit"], r["dataset"], r["n_clients"], r["eps"]): r for r in r8}
        pair = []
        for (meth, unit, ds, n, e), r in idx.items():
            if meth == "m9_contractive":
                base = idx.get(("m0_dpsgd_u1" if unit == "U1" else "m0_dpfedavg_u2", unit, ds, n, e))
                if base:
                    pair.append([unit, ds, n, e, ci3(r), r["edge_axes"], ci3(base), base["edge_axes"],
                                 f"{float(r['final_avg_acc_mean']) - float(base['final_avg_acc_mean']):+.3f}"])
        body = []
        for r in r8:
            pt = f"lr={r['lr']}, mult={r['clip_multiplier']}" if r["p"] == "n/a" else f"p={r['p']}, λ={r['lambda']}"
            body.append([r["method"], r["unit"], r["dataset"], r["n_clients"], r["eps"], pt, ci3(r), f"{float(r['bwt_mean']):.3f}",
                         r["edge_axes"], fv(r["prev_selected_mean"]), fv(r["oracle_best_mean"]), r["oracle_source"]])
        md += ["## R8 symmetric re-selection (TEST-INFORMED DESIGN; selection on public data only)", "",
               "Source: `results/rb_r8_summary.csv` (per seed: `results/rb_r8.csv`; selection grid: `results/rb_r8_selection.csv`); "
               "protocol `rebuttal/R8_PROTOCOL.md`. **The wider grids and the size-matched selection federation were motivated by the "
               "test-split sensitivity results of R7/R7b**, so R8 must be reported as test-informed. Selection itself used only "
               "ref-train / ref-val. Earlier results are unchanged. 'oracle' = R7/R7b test-oracle upper bound, not used for selection "
               f"(n/a where not covered). Selected points on a grid edge: {sum(r['on_edge'] == '1' for r in r8)}/{len(r8)}.", "",
               "M9 vs the DP baseline under the same unit, both re-selected by the same procedure:", "",
               table(["unit", "dataset", "n", "ε0", "M9 [95% CI]", "M9 edge", "baseline [95% CI]", "baseline edge", "M9 − baseline"], pair), "",
               table(["method", "unit", "dataset", "n", "ε0", "selected point", "final avg acc [95% CI]", "BWT", "edge",
                      "R3/R5/paper selected", "R7/R7b oracle", "oracle source"], body), ""]

    OUT.write_text("\n".join(md) + "\n")
    print(f"R6 wrote {OUT} ({len(md)} blocks)")
    provenance.finalize(man, [OUT])
    return 0


if __name__ == "__main__":
    sys.exit(main())
